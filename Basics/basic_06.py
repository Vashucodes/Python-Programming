a = 10
b = 3

# Arithmetic Operators
print("----- Arithmetic Operators -----")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

#Comparison operators
print("\n----- Comparison Operators -----")
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

#Logical operators
print("\n----- Logical Operators -----")
x = True
y = False

print(x and y)
print(x or y)
print(not x)